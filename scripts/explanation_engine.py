def chapter_key(chapter: str) -> str:
    return next((key for key in DEFAULTS if key != "未分类" and chapter.startswith(key)), "未分类")


def pattern_specificity(pattern: str) -> int:
    """Estimate how diagnostic a regex is without rewarding a greedy `.*` match."""
    alternatives = pattern.split("|")
    return max(
        sum(len(token) for token in re.findall(r"[\u4e00-\u9fff]+|[A-Za-z0-9]+", alternative))
        for alternative in alternatives
    )


def select_concept(chapter: str, stem: str, options: dict[str, str]) -> Concept:
    key = chapter_key(chapter)
    combined = " ".join([stem, *options.values()])
    rules = [
        *( (pattern, concept, 1) for pattern, concept in RULES.get(key, []) ),
        *( (pattern, concept, 0) for pattern, concept in GLOBAL_RULES ),
    ]
    # Prefer a precise match in the stem. Only consult all options when the stem
    # itself carries no recognisable concept, because distractors often name a
    # different theory on purpose.
    for search_text in (stem, combined):
        matches: list[tuple[int, int, Concept]] = []
        for index, (pattern, concept, chapter_bonus) in enumerate(rules):
            if re.search(pattern, search_text, flags=re.I):
                matches.append((pattern_specificity(pattern) + chapter_bonus, -index, concept))
        if matches:
            return max(matches, key=lambda item: (item[0], item[1]))[2]
    return DEFAULTS[key]


def compact(text: str, limit: int = 74) -> str:
    text = re.sub(r"\s+", "", text).strip("；;。")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def wrong_reason(text: str, concept: Concept) -> str:
    for pattern, reason in MISCONCEPTIONS:
        if re.search(pattern, text, flags=re.I):
            return reason
    if any(word in concept.title for word in ("创立", "来源", "文献", "人物", "体系", "历史贡献")):
        return "与教材确认的历史事实、代表人物、文献出处或规范分类不符。"
    if re.search(r"决定|根本|本质|源泉", text):
        return "混淆了决定作用、重要影响和一般条件的层次，因而没有准确表达该原理。"
    if re.search(r"无条件|永远|完全|全部|任何|必然都|唯一", text):
        return "把有条件、具体的关系绝对化，超出了该命题成立的范围。"
    return f"没有准确反映“{concept.title}”的规定，或与题干所问的层次和范围不一致。"


