def correct_reason(text: str, concept: Concept) -> str:
    for pattern, reason in CORRECT_REASONS:
        if re.search(pattern, text, flags=re.I):
            return reason
    if any(word in concept.title for word in ("创立", "来源", "文献", "人物", "体系", "历史贡献")):
        return "与教材确认的历史事实、代表人物、文献出处或规范分类相符"
    return f"准确表达了“{concept.title}”在本题条件下的含义，并直接回应题干所问"


def build_explanation(
    stem: str,
    answer: str | None,
    options: dict[str, str],
    chapter: str,
    question_type: str,
) -> str:
    if not answer:
        return "原始资料未提供可靠答案，本题暂不进入正式练习，需人工校对后再补充解析。"

    concept = select_concept(chapter, stem, options)
    selected = [letter for letter in answer if letter in options]
    rejected = [letter for letter in options if letter not in selected]
    if not selected:
        return f"【考点】{concept.title}\n【原理】{concept.principle}\n【结论】原答案与选项不匹配，本题需人工校对。"

    correct_parts = [
        f"{letter}项“{compact(options[letter])}”正确，因为{correct_reason(options[letter], concept)}"
        for letter in selected
    ]
    correct_analysis = "；".join(correct_parts) + "。"

    wrong_parts = [
        f"{letter}项“{compact(options[letter], 52)}”不选，因为{wrong_reason(options[letter], concept).rstrip('。；')}"
        for letter in rejected
    ]
    wrong_analysis = ("；".join(wrong_parts) + "。") if wrong_parts else "其余选项不构成独立干扰项。"
    type_note = "多选题要逐项判断，不能因某一项表述相近就漏选。" if question_type == "multiple" else "单选题应选择与题干限定最完整、最直接对应的一项。"

    return (
        f"【考点】{concept.title}\n"
        f"【原理】{concept.principle}\n"
        f"【选项分析】{correct_analysis}{wrong_analysis}\n"
        f"【结论】正确答案为 {answer}。{type_note}"
    )
