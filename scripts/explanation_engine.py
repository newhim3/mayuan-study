def chapter_key(chapter: str) -> str:
    return next((key for key in DEFAULTS if key != "未分类" and chapter.startswith(key)), "未分类")


def select_concept(chapter: str, stem: str, options: dict[str, str]) -> Concept:
    key = chapter_key(chapter)
    combined = " ".join([stem, *options.values()])
    for search_text in (stem, combined):
        for pattern, concept in RULES.get(key, []):
            if re.search(pattern, search_text, flags=re.I):
                return concept
        for pattern, concept in GLOBAL_RULES:
            if re.search(pattern, search_text, flags=re.I):
                return concept
    return DEFAULTS[key]


def compact(text: str, limit: int = 74) -> str:
    text = re.sub(r"\s+", "", text).strip("；;。")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def wrong_reason(text: str, concept: Concept) -> str:
    for pattern, reason in MISCONCEPTIONS:
        if re.search(pattern, text, flags=re.I):
            return reason
    if any(word in concept.title for word in ("创立", "来源", "文献", "人物", "体系", "历史贡献")):
        return "与教材确认的历史事实、代表人物、文献出处或规范分类不符。"
    if re.search(r"决定|根本|本质|源泉", text):
        return "混淆了决定作用、重要影响和一般条件的层次，因而没有准确表达该原理。"
    if re.search(r"无条件|永远|完全|全部|任何|必然都|唯一", text):
        return "把有条件、具体的关系绝对化，超出了该命题成立的范围。"
    return f"没有准确反映“{concept.title}”的规定，或与题干所问的层次和范围不一致。"


def build_explanation(
    stem: str,
    answer: str | None,
    options: dict[str, str],
    chapter: str,
    question_type: str,
) -> str:
    if not answer:
        return "原始资料未提供可靠答案，本题暂不进入正式练习，需人工校对后再补充解析。"

    concept = select_concept(chapter, stem, options)
    selected = [letter for letter in answer if letter in options]
    rejected = [letter for letter in options if letter not in selected]
    if not selected:
        return f"【考点】{concept.title}\n【原理】{concept.principle}\n【结论】原答案与选项不匹配，本题需人工校对。"

    if len(selected) == 1:
        letter = selected[0]
        correct_analysis = (
            f"{letter}项“{compact(options[letter])}”与上述原理及题干限定相符，"
            "是给定选项中最准确的表述。"
        )
    else:
        parts = [
            f"{letter}项“{compact(options[letter])}”从相应方面体现了该原理"
            for letter in selected
        ]
        correct_analysis = "；".join(parts) + "，这些表述可以同时成立。"

    wrong_parts = [
        f"{letter}项“{compact(options[letter], 52)}”不选，因为{wrong_reason(options[letter], concept).rstrip('。；')}"
        for letter in rejected
    ]
    wrong_analysis = ("；".join(wrong_parts) + "。") if wrong_parts else "其余选项不构成独立干扰项。"
    type_note = "多选题要逐项判断，不能因某一项表述相近就漏选。" if question_type == "multiple" else "单选题应选择与题干限定最完整、最直接对应的一项。"

    return (
        f"【考点】{concept.title}\n"
        f"【原理】{concept.principle}\n"
        f"【选项分析】{correct_analysis}{wrong_analysis}\n"
        f"【结论】正确答案为 {answer}。{type_note}"
    )
